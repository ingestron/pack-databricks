// Turns the resolved model into the bundle's files, path → text. The files are
// built as data first, so that folding environments together can change them.
import type { ResolvedModel } from "@ingestron/definitions";
import {
  bundleFile,
  eventLog,
  jobFile,
  pipelineExtras,
  pipelineFile,
  pipelineTags,
  schemaKeys,
  schemasFile,
  withAlerts,
  yamlText,
  type Data,
  type Task,
} from "../bundle/index.js";
import {
  connectGroups,
  gatewayPipeline,
  ingestionPipeline,
  previewNote,
  type ConnectGroup,
} from "../connect/index.js";
import { applyContract } from "../sql/index.js";
import { prerequisites } from "../methods/index.js";
import { renderApply, renderSql, sqlFile } from "../sql/index.js";

const doNotEdit = "Do not edit: change the definitions and generate again.";

/** A YAML file as data, with its header comments. */
export interface YamlFile {
  headers: string[];
  data: Data;
}

/** The bundle's files before they are written: YAML as data, code as text. */
export interface BundleData {
  /** By path, in the order they are built. */
  files: Record<string, YamlFile | string>;
  /** The definition file each table's code file comes from, by path. */
  origins: Record<string, string>;
}

/**
 * Every file of the bundle for one environment: one target, every value as resolved.
 * @example
 * const files = build(model); // { "databricks.yml": "...", "src/retail/bronze/orders.sql": "..." }
 */
export function build(model: ResolvedModel): Record<string, string> {
  return written(bundleData(withAlerts(model)).files);
}

/** The files as text. */
export function written(files: BundleData["files"]): Record<string, string> {
  return Object.fromEntries(
    Object.entries(files).map(([path, file]) => [
      path,
      typeof file === "string" ? file : yamlText(file.headers, file.data),
    ]),
  );
}

/** The header of the bundle's own files. */
export function headerOf(model: ResolvedModel): string {
  return `Generated by Ingestron from the ${model.project.id} definitions. ${doNotEdit}`;
}

/** Every file of the bundle for one environment, as data, from a model built `withAlerts`. */
export function bundleData(model: ResolvedModel): BundleData {
  const header = headerOf(model);
  const keys = schemaKeys(model);
  const groups = connectGroups(model);
  const files: BundleData["files"] = {
    "databricks.yml": { headers: [header], data: bundleFile(model) },
  };
  const output = { header, keys, files, origins: {} };
  const refreshes = [...connectFiles(model, groups, output), ...sqlFiles(model, groups, output)];
  const tasks = [...refreshes, ...applyFiles(model, refreshes, output)];
  const job = jobFile(model, tasks);
  if (job) files[`resources/${model.names.job}.job.yml`] = { headers: [header], data: job };
  const schemas = schemasFile(model, keys);
  if (schemas) files["resources/schemas.yml"] = { headers: [header], data: schemas };
  const needs = prerequisites(model, header);
  if (needs) files[`prerequisites/${model.project.environment}.sql`] = needs;
  return { files, origins: output.origins };
}

/** What every file builder needs: the header, the managed schema keys and the files so far. */
interface Output extends BundleData {
  header: string;
  keys: Map<string, string>;
}

/** Lakeflow Connect pipelines; returns the job tasks for those the job refreshes. */
function connectFiles(model: ResolvedModel, groups: ConnectGroup[], output: Output): Task[] {
  const { header, keys, files } = output;
  return groups.flatMap((group) => {
    const headers = [header, previewNote(group)];
    if (group.gateway) {
      const gateway = { ...gatewayPipeline(group, keys), ...pipelineTags(model) };
      const data = { resources: { pipelines: { [group.gateway]: gateway } } };
      files[`resources/${group.gateway}.pipeline.yml`] = { headers, data };
    }
    const ingestion = ingestionPipeline(group, keys);
    const pipeline = { ...ingestion, ...pipelineExtras(model), ...eventLog(model, ingestion) };
    const data = { resources: { pipelines: { [group.ingestion]: pipeline } } };
    files[`resources/${group.ingestion}.pipeline.yml`] = { headers, data };
    return group.continuous
      ? []
      : [{ key: `ingest_${group.connection.id}`, pipeline: group.ingestion, after: [] }];
  });
}

/** Our own pipeline and its SQL files, refreshed after every ingestion task. */
function sqlFiles(model: ResolvedModel, groups: ConnectGroup[], output: Output): Task[] {
  const { keys, files } = output;
  const tables = model.tables.filter((table) => table.store);
  if (tables.length === 0) return [];
  const { pipeline } = model.names;
  const data = pipelineFile(model, tables, keys);
  files[`resources/${pipeline}.pipeline.yml`] = { headers: [output.header], data };
  const catalog = tables[0]!.fullName.catalog;
  for (const table of tables) {
    const tableHeader = `Generated by Ingestron from ${table.origin.file} (table ${table.name}). ${doNotEdit}`;
    const file = sqlFile(table, tableHeader, catalog);
    const path = `src/${pipeline}/${table.layer}/${table.name}.${file.extension}`;
    files[path] = renderSql(file);
    output.origins[path] = table.origin.file;
  }
  const ingestion = groups
    .filter((group) => !group.continuous)
    .map((group) => `ingest_${group.connection.id}`);
  return [{ key: "refresh", pipeline, after: ingestion }];
}

/**
 * The after-refresh script's path: in `tasks/`, outside every pipeline's `src/<pipeline>/**`
 * sources whatever the naming standard, so that no pipeline loads it as its own code.
 */
export function scriptPath(pipeline: string): string {
  return `tasks/${pipeline}/apply_contract.py`;
}

/** The Python file that applies tags, comments and table checks after every refresh. */
function applyFiles(model: ResolvedModel, refreshes: Task[], output: Output): Task[] {
  const { statements, checks } = applyContract(model);
  if (statements.length === 0 && checks.length === 0) return [];
  const path = scriptPath(model.names.pipeline);
  output.files[path] = renderApply({ header: output.header, statements, checks });
  return [
    { key: "apply_contract", python: `../${path}`, after: refreshes.map((task) => task.key) },
  ];
}
