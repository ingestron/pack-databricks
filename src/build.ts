// Turns the resolved model into the bundle's files, path → text.
import type { ResolvedModel } from "@ingestron/definitions";
import {
  bundleFile,
  jobFile,
  pipelineExtras,
  pipelineFile,
  schemaKeys,
  schemasFile,
  yamlText,
  type Task,
} from "./bundle.js";
import {
  connectGroups,
  gatewayPipeline,
  ingestionPipeline,
  previewNote,
  type ConnectGroup,
} from "./connect.js";
import { applyContract } from "./apply-contract.js";
import { prerequisites } from "./capabilities.js";
import { renderApply, renderSql, sqlFile } from "./sql.js";

const doNotEdit = "Do not edit: change the definitions and generate again.";

/**
 * Every file of the bundle for one environment.
 * @example
 * const files = build(model); // { "databricks.yml": "...", "src/retail/bronze/orders.sql": "..." }
 */
export function build(model: ResolvedModel): Record<string, string> {
  const header = `Generated by Ingestron from the ${model.project.id} definitions (${model.project.environment}). ${doNotEdit}`;
  const keys = schemaKeys(model);
  const groups = connectGroups(model);
  const files: Record<string, string> = { "databricks.yml": yamlText(header, bundleFile(model)) };
  const output = { header, keys, files };
  const refreshes = [...connectFiles(model, groups, output), ...sqlFiles(model, groups, output)];
  const tasks = [...refreshes, ...applyFiles(model, refreshes, output)];
  const job = jobFile(model, tasks);
  if (job) files[`resources/${model.names.job}.job.yml`] = yamlText(header, job);
  const schemas = schemasFile(model, keys);
  if (schemas) files["resources/schemas.yml"] = yamlText(header, schemas);
  const needs = prerequisites(model, header);
  if (needs) files["prerequisites.sql"] = needs;
  return files;
}

/** What every file builder needs: the header, the managed schema keys and the files so far. */
interface Output {
  header: string;
  keys: Map<string, string>;
  files: Record<string, string>;
}

/** Lakeflow Connect pipelines; returns the job tasks for those the job refreshes. */
function connectFiles(model: ResolvedModel, groups: ConnectGroup[], output: Output): Task[] {
  const { header, keys, files } = output;
  return groups.flatMap((group) => {
    const headers = [header, previewNote(group)];
    if (group.gateway) {
      const gateway = {
        resources: { pipelines: { [group.gateway]: gatewayPipeline(group, keys) } },
      };
      files[`resources/${group.gateway}.pipeline.yml`] = yamlText(headers, gateway);
    }
    const pipeline = { ...ingestionPipeline(group, keys), ...pipelineExtras(model) };
    const ingestion = { resources: { pipelines: { [group.ingestion]: pipeline } } };
    files[`resources/${group.ingestion}.pipeline.yml`] = yamlText(headers, ingestion);
    return group.continuous
      ? []
      : [{ key: `ingest_${group.connection.id}`, pipeline: group.ingestion, after: [] }];
  });
}

/** Our own pipeline and its SQL files, refreshed after every ingestion task. */
function sqlFiles(model: ResolvedModel, groups: ConnectGroup[], output: Output): Task[] {
  const { keys, files } = output;
  const tables = model.tables.filter((table) => table.store);
  if (tables.length === 0) return [];
  const { pipeline } = model.names;
  files[`resources/${pipeline}.pipeline.yml`] = yamlText(
    output.header,
    pipelineFile(model, tables, keys),
  );
  for (const table of tables) {
    const tableHeader = `Generated by Ingestron from ${table.origin.file} (table ${table.name}). ${doNotEdit}`;
    const file = sqlFile(table, tableHeader);
    files[`src/${pipeline}/${table.layer}/${table.name}.${file.extension}`] = renderSql(file);
  }
  const ingestion = groups
    .filter((group) => !group.continuous)
    .map((group) => `ingest_${group.connection.id}`);
  return [{ key: "refresh", pipeline, after: ingestion }];
}

/** The Python file that applies tags, comments and table checks after every refresh. */
function applyFiles(model: ResolvedModel, refreshes: Task[], output: Output): Task[] {
  const { statements, checks } = applyContract(model);
  if (statements.length === 0 && checks.length === 0) return [];
  const path = `src/${model.names.pipeline}/apply_contract.py`;
  output.files[path] = renderApply({ header: output.header, statements, checks });
  return [
    { key: "apply_contract", python: `../${path}`, after: refreshes.map((task) => task.key) },
  ];
}
