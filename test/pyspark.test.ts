// PySpark transforms: the user's transform(tables) function, wrapped as a
// materialised view with the pipelines Python API.
import { describe, expect, it } from "vitest";
import { contract, generate } from "./connect-helpers.js";

const files = {
  "shop.yaml":
    "apiVersion: ingestron.io/v1\nkind: Connection\nid: shop\nconnector: files\nconnectivity: public\nsettings: { path: /Volumes/dev/landing/shop }\n",
  "orders.flow.yaml":
    "apiVersion: ingestron.io/v1\nkind: Flow\nid: shop\nsource: shop\ntables:\n  orders: { object: orders, contract: orders }\n",
  "orders.yaml": contract("orders"),
  "totals.yaml": contract("totals"),
  "totals.t.yaml": [
    "apiVersion: ingestron.io/v1",
    "kind: Transform",
    "id: totals",
    "inputs: [orders]",
    "contract: totals",
    "transform: { uses: pyspark }",
    "expectations:",
    "  - { name: positive, check: total > 0, action: drop }",
    "code: |",
    "  from pyspark.sql import functions as F",
    "",
    "  def transform(tables):",
    '      return tables["orders"].groupBy("id").agg(F.sum("total").alias("total"))',
    "",
  ].join("\n"),
};

describe("PySpark transforms", () => {
  it("writes a Python file that copies the code and wraps it as a materialised view", () => {
    const { output } = generate(files);
    expect(output["src/shop/silver/totals.sql"]).toBeUndefined();
    expect(output["src/shop/silver/totals.py"]).toBe(
      [
        "# Generated by Ingestron from totals.t.yaml (table totals). Do not edit: change the definitions and generate again.",
        "from pyspark import pipelines as dp",
        "",
        "# The transform's own code, unchanged:",
        "from pyspark.sql import functions as F",
        "",
        "def transform(tables):",
        '    return tables["orders"].groupBy("id").agg(F.sum("total").alias("total"))',
        "",
        "",
        "@dp.materialized_view(",
        '    name="dev.silver.totals",',
        "    cluster_by_auto=True,",
        ")",
        '@dp.expect_all({"id_not_null": "`id` IS NOT NULL"})',
        '@dp.expect_all_or_drop({"positive": "total > 0"})',
        "def ingestron_totals():",
        "    return transform({",
        '        "orders": spark.read.table("dev.bronze.orders"),',
        "    })",
        "",
      ].join("\n"),
    );
  });

  it("refuses code without the function it calls", () => {
    const code = files["totals.t.yaml"].replace("def transform(tables):", "def build(tables):");
    const { result } = generate({ ...files, "totals.t.yaml": code });
    expect(result.diagnostics[0]?.message).toBe(
      '"pyspark" for table "totals": the code has no function "def transform(tables)".',
    );
  });

  it("ignores tables[...] in comments", () => {
    const code = files["totals.t.yaml"].replace(
      "  def transform(tables):",
      '  # tables["sales"] was the old name\n  def transform(tables):',
    );
    expect(generate({ ...files, "totals.t.yaml": code }).result.diagnostics).toEqual([]);
  });

  it("refuses code that reads an input the transform does not have", () => {
    const code = files["totals.t.yaml"].replace('tables["orders"]', 'tables["sales"]');
    const { result } = generate({ ...files, "totals.t.yaml": code });
    expect(result.diagnostics[0]?.message).toBe(
      '"pyspark" for table "totals": the code reads tables["sales"], which is not an input; the inputs are "orders".',
    );
  });
});
